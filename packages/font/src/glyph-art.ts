/** The merged code-point → string-art table (all printable ASCII). */
export const GLYPH_ART_BY_CODEPOINT: ReadonlyMap<number, readonly string[]> = (() => {
  const map = new Map<number, readonly string[]>();
  for (const table of [GLYPH_ART, UPPERCASE_ART, LOWERCASE_ART, PUNCT2_ART]) {
    for (const [ch, art] of Object.entries(table)) {
      map.set(ch.codePointAt(0)!, art);
    }
  }
  return map;
})();
